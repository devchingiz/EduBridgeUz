import "server-only";

import fs from "node:fs/promises";
import path from "node:path";
import nodemailer, { type Transporter } from "nodemailer";

import { getEmailConfig, getEmailFrom } from "@/lib/env";
import { logInfo, logWarn } from "@/lib/observability/logger";

export type MailMessage = {
  to: string;
  subject: string;
  text: string;
  html: string;
  tag: string;
};

export const EMAIL_SEND_MAX_ATTEMPTS = 3;

const RETRY_BASE_MS = 250;
const TRANSIENT_SMTP_CODES = new Set([
  "EAI_AGAIN",
  "ECONNABORTED",
  "ECONNREFUSED",
  "ECONNRESET",
  "ECONNECTION",
  "EDNS",
  "EHOSTUNREACH",
  "ENETUNREACH",
  "ENOTFOUND",
  "EPIPE",
  "ESOCKET",
  "ETIMEDOUT",
  "ETLS",
]);
const BODY_PHASE_COMMANDS = new Set(["BDAT", "DATA", "DOT"]);

type SmtpFailure = {
  code?: unknown;
  command?: unknown;
  responseCode?: unknown;
};

function failureMetadata(error: unknown): SmtpFailure {
  return error && typeof error === "object" ? (error as SmtpFailure) : {};
}

function retryReason(error: unknown): string | undefined {
  const { code, responseCode } = failureMetadata(error);
  if (
    typeof responseCode === "number" &&
    responseCode >= 400 &&
    responseCode < 500
  ) {
    return String(responseCode);
  }
  if (typeof code === "string" && /^[A-Za-z0-9_]{1,32}$/.test(code)) {
    return code;
  }
  return undefined;
}

function shouldRetrySmtpFailure(error: unknown): boolean {
  const { code, command, responseCode } = failureMetadata(error);

  // Once the message body has been handed over, a retry could deliver a
  // duplicate even if the server reported a failure afterwards.
  if (
    typeof command === "string" &&
    BODY_PHASE_COMMANDS.has(command.toUpperCase())
  ) {
    return false;
  }

  if (typeof responseCode === "number") {
    if (responseCode >= 500) return false;
    if (responseCode >= 400) return true;
  }

  return (
    typeof code === "string" && TRANSIENT_SMTP_CODES.has(code.toUpperCase())
  );
}

function sleep(ms: number): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

let transporter: Transporter | undefined;

function getTransporter(): Transporter {
  const config = getEmailConfig();
  if (config.transport !== "smtp") {
    throw new Error("SMTP transport requested but not configured.");
  }

  transporter ??= nodemailer.createTransport({
    host: config.host,
    port: config.port,
    secure: config.secure,
    connectionTimeout: 5_000,
    greetingTimeout: 5_000,
    socketTimeout: 10_000,
    auth:
      config.user && config.password
        ? { user: config.user, pass: config.password }
        : undefined,
  });

  return transporter;
}

/**
 * Development transport: writes each message to `.data/mail/` so verification
 * and reset links can be inspected without an SMTP server. Never enabled in
 * production (see `getEmailConfig`).
 */
async function writeToOutbox(message: MailMessage): Promise<void> {
  const directory = path.join(process.cwd(), ".data", "mail");
  await fs.mkdir(directory, { recursive: true });

  const stamp = new Date().toISOString().replace(/[:.]/g, "-");
  const safeRecipient = message.to.replace(/[^a-z0-9@._-]/gi, "_");
  const file = path.join(
    directory,
    `${stamp}-${message.tag}-${safeRecipient}.json`,
  );

  await fs.writeFile(
    file,
    JSON.stringify(
      {
        to: message.to,
        subject: message.subject,
        text: message.text,
        html: message.html,
        tag: message.tag,
        createdAt: new Date().toISOString(),
      },
      null,
      2,
    ),
    "utf8",
  );

  logInfo("email.console_outbox_written", { tag: message.tag });
}

export async function sendMail(message: MailMessage): Promise<void> {
  const config = getEmailConfig();

  if (config.transport === "console") {
    await writeToOutbox(message);
    return;
  }

  // Build the payload once. Retries reuse the same prepared message; tokens
  // and templates are never regenerated by the retry loop.
  const payload = {
    from: getEmailFrom(),
    to: message.to,
    subject: message.subject,
    text: message.text,
    html: message.html,
  };
  const transporter = getTransporter();

  for (let attempt = 1; attempt <= EMAIL_SEND_MAX_ATTEMPTS; attempt += 1) {
    try {
      await transporter.sendMail(payload);
      return;
    } catch (error) {
      if (
        attempt === EMAIL_SEND_MAX_ATTEMPTS ||
        !shouldRetrySmtpFailure(error)
      ) {
        throw error;
      }

      const delayMs = RETRY_BASE_MS * 2 ** (attempt - 1);
      logWarn("email.delivery_retry", {
        tag: message.tag,
        attempt,
        delayMs,
        reason: retryReason(error),
      });
      await sleep(delayMs);
    }
  }
}
